export function buildGeorgianSchemas(page) {
  const breadcrumbs = [
    { "@type": "ListItem", position: 1, name: "მთავარი", item: GEORGIAN_SITE_URL },
    { "@type": "ListItem", position: 2, name: page.h1, item: page.url },
  ];
  const schemas = [
    {
      "@context": "https://schema.org",
      "@type": "WebPage",
      "@id": `${page.url}/#webpage`,
      url: page.url,
      name: page.title,
      description: page.description,
      inLanguage: "ka-GE",
      isPartOf: { "@id": `${GEORGIAN_SITE_URL}/#website` },
      about: page.serviceType,
    },
    { "@context": "https://schema.org", "@type": "BreadcrumbList", "@id": `${page.url}/#breadcrumbs`, itemListElement: breadcrumbs },
    {
      "@context": "https://schema.org",
      "@type": "Service",
      "@id": `${page.url}/#service`,
      name: page.serviceType,
      serviceType: page.serviceType,
      url: page.url,
      description: page.description,
      provider: { "@id": `${GEORGIAN_SITE_URL}/#organization` },
      areaServed: "საქართველო",
      availableLanguage: "ka-GE",
    },
  ];
  if (page.faqs?.length) {
    schemas.push({
      "@context": "https://schema.org",
      "@type": "FAQPage",
      "@id": `${page.url}/#faq`,
      mainEntity: page.faqs.map((faq) => ({
        "@type": "Question",
        name: faq.question,
        acceptedAnswer: { "@type": "Answer", text: faq.answer },
      })),
    });
  }
  return schemas;
}
